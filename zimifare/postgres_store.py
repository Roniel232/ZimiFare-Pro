"""Persistent PostgreSQL backend for the existing ZimiFare business rules.

ZimiFare's existing core.py remains the single source of business logic.  This
adapter maps its tiny SQLite-style query interface to Psycopg 3/PostgreSQL and
keeps all writes serialised with a database-wide transactional advisory lock.
All monetary updates, duplicate-payment checks and associated rows commit or
roll back together, including when two users access Streamlit simultaneously.
"""
from __future__ import annotations

import os
import re
import sqlite3
from contextlib import contextmanager
from typing import Any, Iterator

from .core import ZimiFareStore

# Database-scoped lock ID. One lock serialises every write transaction.
# This deliberately mirrors core.py's SQLite BEGIN IMMEDIATE behaviour.
ZIMIFARE_WRITE_LOCK = 743_966_200_101


class _Row(dict):
    """Dict-style rows compatible with core.py's occasional row[0] queries."""
    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


class _Cursor:
    def __init__(self, raw: Any, lastrowid: int | None = None) -> None:
        self.raw = raw
        self.lastrowid = lastrowid

    def fetchone(self) -> _Row | None:
        row = self.raw.fetchone()
        return _Row(row) if row is not None else None

    def fetchall(self) -> list[_Row]:
        return [_Row(r) for r in self.raw.fetchall()]


_INSERT_IDS = {"users": "user_id", "rides": "ride_id", "transactions": "transaction_id"}
_INSERT_REGEX = re.compile(r"^\s*INSERT\s+INTO\s+(users|rides|transactions)\b", re.I)


class _Connection:
    """Adapter translating the known, parameterized core.py SQL operations."""
    def __init__(self, raw: Any) -> None:
        self.raw = raw

    def execute(self, sql: str, params: Any = None) -> _Cursor:
        # The SQL supplied by core.py has ? placeholders only, never literal
        # question-mark operators. Values remain parameters, never interpolated.
        match = _INSERT_REGEX.match(sql)
        sql = sql.replace("?", "%s")
        if match:
            sql += f" RETURNING {_INSERT_IDS[match.group(1).lower()]}"
        try:
            cursor = self.raw.execute(sql, tuple(params) if params is not None else None)
        except Exception as exc:
            # Preserve the existing registration's duplicate-email error flow.
            if getattr(exc, "sqlstate", None) == "23505":
                raise sqlite3.IntegrityError("UNIQUE constraint failed") from exc
            raise
        if match:
            inserted = cursor.fetchone()
            return _Cursor(cursor, int(next(iter(inserted.values()))))
        return _Cursor(cursor)


class PostgresZimiFareStore(ZimiFareStore):
    """The identical ZimiFare API backed by hosted PostgreSQL instead of SQLite."""
    backend_name = "PostgreSQL (persistent)"

    def __init__(self, database_url: str) -> None:
        if not database_url or not database_url.startswith(("postgresql://", "postgres://")):
            raise ValueError("DATABASE_URL must be a PostgreSQL connection string.")
        self._database_url = database_url
        self.init_db()

    def _connect(self) -> _Connection:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError('Install dependencies using: pip install -r requirements.txt') from exc
        raw = psycopg.connect(self._database_url, autocommit=True, row_factory=dict_row, connect_timeout=15)
        return _Connection(raw)

    @contextmanager
    def _read(self) -> Iterator[_Connection]:
        conn = self._connect()
        try:
            yield conn
        finally:
            conn.raw.close()

    @contextmanager
    def _write(self) -> Iterator[_Connection]:
        conn = self._connect()
        try:
            with conn.raw.transaction():
                # A transaction-scoped lock makes the checked-then-inserted
                # writes linearizable across users, threads, and processes.
                conn.execute("SELECT pg_advisory_xact_lock(%s)", (ZIMIFARE_WRITE_LOCK,))
                yield conn
        finally:
            conn.raw.close()

    def init_db(self) -> None:
        ddl = [
            """CREATE TABLE IF NOT EXISTS users (
                user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                full_name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                phone_num TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL CHECK(role IN ('PASSENGER','DRIVER','ADMIN')),
                status TEXT NOT NULL DEFAULT 'ACTIVE'
                    CHECK(status IN ('ACTIVE','DISABLED','BLOCKED')),
                balance_cents BIGINT NOT NULL DEFAULT 0 CHECK(balance_cents >= 0)
            )""",
            """CREATE TABLE IF NOT EXISTS rides (
                ride_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                passenger_id INTEGER NOT NULL REFERENCES users(user_id),
                driver_id INTEGER NOT NULL REFERENCES users(user_id),
                ride_date TEXT NOT NULL,
                pickup TEXT NOT NULL,
                destination TEXT NOT NULL,
                fare_cents BIGINT NOT NULL CHECK(fare_cents > 0),
                payment_status TEXT NOT NULL DEFAULT 'UNPAID'
                    CHECK(payment_status IN ('UNPAID','PAID')),
                payment_method TEXT NOT NULL DEFAULT 'NONE'
                    CHECK(payment_method IN ('NONE','FARE_CARD','CASH')),
                transaction_id INTEGER UNIQUE
            )""",
            """CREATE TABLE IF NOT EXISTS transactions (
                transaction_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                tx_type TEXT NOT NULL CHECK(tx_type IN ('TOP_UP','FARE_PAYMENT')),
                passenger_id INTEGER NOT NULL REFERENCES users(user_id),
                driver_id INTEGER REFERENCES users(user_id),
                ride_id INTEGER REFERENCES rides(ride_id),
                amount_cents BIGINT NOT NULL CHECK(amount_cents > 0),
                method TEXT NOT NULL CHECK(method IN ('SIMULATED_TOP_UP','FARE_CARD','CASH')),
                recorded_by INTEGER NOT NULL REFERENCES users(user_id),
                recorded_at TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'SUCCESS' CHECK(status = 'SUCCESS'),
                flagged SMALLINT NOT NULL DEFAULT 0 CHECK(flagged IN (0,1))
            )""",
            """CREATE UNIQUE INDEX IF NOT EXISTS one_payment_per_ride
                ON transactions(ride_id) WHERE tx_type='FARE_PAYMENT'""",
            "CREATE INDEX IF NOT EXISTS idx_rides_passenger ON rides(passenger_id)",
            "CREATE INDEX IF NOT EXISTS idx_rides_driver ON rides(driver_id)",
            "CREATE INDEX IF NOT EXISTS idx_transactions_passenger ON transactions(passenger_id)",
        ]
        conn = self._connect()
        try:
            with conn.raw.transaction():
                conn.execute("SELECT pg_advisory_xact_lock(%s)", (ZIMIFARE_WRITE_LOCK,))
                for sql in ddl:
                    conn.execute(sql)
        finally:
            conn.raw.close()


def get_zimifare_store(database_url: str | None = None) -> ZimiFareStore:
    """Use cloud database if DATABASE_URL exists; otherwise preserve local SQLite.

    Streamlit Community Cloud exposes top-level app secrets as environment
    variables, so DATABASE_URL can be configured without putting it in GitHub.
    """
    url = (database_url or os.environ.get("DATABASE_URL", "")).strip()
    if url:
        return PostgresZimiFareStore(url)
    return ZimiFareStore()
